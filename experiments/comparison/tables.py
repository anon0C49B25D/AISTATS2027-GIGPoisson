"""The comparison tables the manuscript inputs, written into ``experiments/tables/``.

    small_catalogue.tex   NLPD at the full budget against the size of the calibration
                          catalogue, per setting: GIG-Poisson, and the gamma-Poisson and the
                          gamma mixture as their paired difference from it
    lsn.tex               GIG-Poisson against the three log-skew-normal implementations:
                          NLPD at the full budget and wall-clock time per round

Reads ``results/<prefix><setting>.csv`` and ``results/significance.csv``. A table row whose
results are not on disk is left out, so the script can run while the study is incomplete.

Run: python experiments/comparison/tables.py
"""

import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
RESULTS = os.path.join(HERE, "results")
OUT = os.path.join(ROOT, "experiments", "tables")
HEADER = "% Generated by experiments/comparison/tables.py. Do not edit by hand.\n"

SETTINGS = ("bulk", "gamma", "hardxray")
#: Catalogue sizes per setting, as (results prefix, row label). The paper's setting is the
#: unprefixed one. The largest catalogue is the whole population half of a class in the
#: telescope settings and, since bulk sampling is simulated, 200 blocks per facies there.
SIZES = {"bulk": (("", "20"), ("pop40_", "40"), ("pop200_", "large")),
         "gamma": (("", "20"), ("pop40_", "40"), ("popall_", "large")),
         "hardxray": (("", "20"), ("pop40_", "40"), ("popall_", "large"))}
RIVALS = ("eig@gamma-poisson", "eig@gammamix-poisson")
LSN = (("eig", "GIG-Poisson (ours)"),
       ("eig@logskewnormal-quad", "skew-normal, quadrature"),
       ("eig@logskewnormal-poisson", "skew-normal, MCMC, $M = 1024$"),
       ("eig@logskewnormal-poisson-m8k", "skew-normal, MCMC, $M = 8192$"))


def final(name):
    path = os.path.join(RESULTS, name + ".csv")
    if not os.path.exists(path):
        return None
    d = pd.read_csv(path)
    d["ms"] = 1e3 * (d.act_seconds + d.observe_seconds) / d.rounds.clip(lower=1)
    return d[np.isclose(d.spent, d.spent.max())]


def wide(fin, column):
    return fin.pivot(index="episode", columns="agent", values=column)


def small_catalogue():
    rows = {}
    for setting in SETTINGS:
        for prefix, label in SIZES[setting]:
            fin = final(prefix + setting)
            if fin is None:
                continue
            w = wide(fin, "nlpd")
            if "eig" not in w or not all(r in w for r in RIVALS):
                continue
            cells = ["${:.3f}$".format(w["eig"].mean())]
            for r in RIVALS:
                cells.append("${:+.3f}$".format((w[r] - w["eig"]).mean()))
            rows.setdefault(label if setting != "bulk" else label, {})[setting] = cells
    order = ("20", "40", "large")
    lines = [HEADER, "\\begin{tabular}{l ccc ccc ccc}\n", "    \\toprule\n",
             "    & \\multicolumn{3}{c}{diamonds} & \\multicolumn{3}{c}{$\\gamma$-ray survey}"
             " & \\multicolumn{3}{c}{hard X-ray} \\\\\n",
             "    \\cmidrule(lr){2-4} \\cmidrule(lr){5-7} \\cmidrule(lr){8-10}\n",
             "    members per class & GIG & gamma & mixture & GIG & gamma & mixture & GIG & "
             "gamma & mixture \\\\\n", "    \\midrule\n"]
    for label in order:
        if label not in rows:
            continue
        cells = []
        for setting in SETTINGS:
            cells += rows[label].get(setting, ["--"] * 3)
        name = {"large": "$200$ / all"}.get(label, "${}$".format(label))
        lines.append("    {} & {} \\\\\n".format(name, " & ".join(cells)))
    lines += ["    \\bottomrule\n", "\\end{tabular}\n"]
    return "".join(lines)


def lsn():
    sig = os.path.join(RESULTS, "significance.csv")
    sig = pd.read_csv(sig) if os.path.exists(sig) else None
    nl, ms = {}, {}
    for setting in SETTINGS:
        fin = final(setting)
        if fin is None:
            continue
        w, t = wide(fin, "nlpd"), wide(fin, "ms")
        for agent, _ in LSN:
            if agent not in w:
                continue
            mark = ""
            if sig is not None and agent != "eig":
                s = sig[(sig.setting == setting) & (sig.metric == "nlpd") & (sig.how == "final")
                        & (((sig.a == "eig") & (sig.b == agent))
                           | ((sig.a == agent) & (sig.b == "eig")))]
                if len(s) and max(s.p_t_holm.iloc[0], s.p_wilcoxon_holm.iloc[0]) < 0.001:
                    mark = "^{*}"
            nl[(agent, setting)] = "${:.3f}{}$".format(w[agent].mean(), mark)
            ms[(agent, setting)] = "${:,.0f}$".format(t[agent].mean()).replace(",", "{,}")
    lines = [HEADER, "\\begin{tabular}{lcccccc}\n", "    \\toprule\n",
             "    & \\multicolumn{3}{c}{NLPD (nats)} & "
             "\\multicolumn{3}{c}{time per round (ms)} \\\\\n",
             "    \\cmidrule(lr){2-4} \\cmidrule(lr){5-7}\n",
             "    model & diamonds & $\\gamma$-ray & hard X-ray & diamonds & $\\gamma$-ray & "
             "hard X-ray \\\\\n", "    \\midrule\n"]
    for agent, label in LSN:
        cells = [nl.get((agent, s), "--") for s in SETTINGS]
        cells += [ms.get((agent, s), "--") for s in SETTINGS]
        lines.append("    {} & {} \\\\\n".format(label, " & ".join(cells)))
    lines += ["    \\bottomrule\n", "\\end{tabular}\n"]
    return "".join(lines)


#: The prior-by-rule factorial of Section 6 (results prefix ``fact_``): rows are
#: (agent, prior label, rule label); the first is the reference every other is paired with.
FACTORIAL = (("eig", "GIG", "EIG"), ("d-optimality", "GIG", "D-optimality"),
             ("systematic", "GIG", "systematic"),
             ("eig@gammamix-poisson", "gamma mixture", "EIG"),
             ("d-optimality@gammamix-poisson", "gamma mixture", "D-optimality"),
             ("systematic@gammamix-poisson", "gamma mixture", "systematic"),
             ("eig@gamma-poisson", "gamma", "EIG"),
             ("d-optimality@gamma-poisson", "gamma", "D-optimality"),
             ("systematic@gamma-poisson", "gamma", "systematic"))
#: Prior-only rows: ``results/prior_only.csv`` model name, label.
PRIOR_ONLY = (("gig-poisson", "GIG"), ("gammamix-poisson", "gamma mixture"),
              ("gamma-poisson", "gamma"))
#: The estimator ablation and the in-regime rivals, all selecting by EIG.
ESTIMATORS = (("eig@gig-pce", "GIG", "EIG by PCE"), ("eig@gig-nmc", "GIG", "EIG by nested MC"),
              ("eig@compoundgamma-poisson", "compound gamma", "EIG"),
              ("eig@logskewnormal-quad-pen", "skew-normal (pen.)", "EIG"))


def _paired(w, a, ref="eig"):
    """Mean of ``a - ref`` over episodes and the half-width of its 95 per cent interval."""
    from scipy import stats
    d = (w[a] - w[ref]).dropna()
    half = stats.t.ppf(0.975, d.size - 1) * d.std(ddof=1) / np.sqrt(d.size)
    return d.mean(), half


#: Fewest paired episodes a table cell is computed from; an agent whose runs are incomplete
#: is shown as "--" rather than as a mean over a few episodes.
MIN_EPISODES = 50


def _cell(w, a, ref="eig", fmt="{:.3f}"):
    if a not in w or ref not in w or (w[a] - w[ref]).dropna().size < MIN_EPISODES:
        return "--"
    if a == ref:
        return "$" + fmt.format(w[a].mean()) + "$"
    m, half = _paired(w, a, ref)
    mean = "0.000" if abs(m) < 5e-4 else "{:+.3f}".format(m)
    return "${}$\\,{{\\scriptsize$\\pm{:.3f}$}}".format(mean, half)


def factorial(prefix="fact_"):
    """NLPD at the full budget and the area under the top-5 regret curve, per setting.

    The GIG under EIG is given absolutely; every other row as its mean paired difference
    from it over the episodes, with the half-width of a 95 per cent t-interval. Positive
    means the row is worse on both metrics. The prior-only rows score each fitted prior
    before any count, at zero budget, paired with the GIG prior.
    """
    cols = {}
    for setting in SETTINGS:
        path = os.path.join(RESULTS, prefix + setting + ".csv")
        if not os.path.exists(path):
            continue
        d = pd.read_csv(path)
        fin = d[np.isclose(d.spent, d.spent.max())]
        cols[setting] = (wide(fin, "nlpd"),
                         d.groupby(["episode", "agent"]).regret_top5.mean().unstack("agent"))
    po = os.path.join(RESULTS, "prior_only.csv")
    po = pd.read_csv(po) if os.path.exists(po) else None
    lines = [HEADER, "\\begin{tabular}{ll cc cc cc}\n", "    \\toprule\n",
             "    & & \\multicolumn{2}{c}{diamonds} & \\multicolumn{2}{c}{$\\gamma$-ray survey}"
             " & \\multicolumn{2}{c}{hard X-ray} \\\\\n",
             "    \\cmidrule(lr){3-4} \\cmidrule(lr){5-6} \\cmidrule(lr){7-8}\n",
             "    prior & rule & NLPD & regret & NLPD & regret & NLPD & regret \\\\\n",
             "    \\midrule\n"]

    def row(agent, prior, rule):
        cells = []
        for setting in SETTINGS:
            if setting not in cols:
                cells += ["--", "--"]
                continue
            w, auc = cols[setting]
            cells += [_cell(w, agent), _cell(auc, agent)]
        return "    {} & {} & {} \\\\\n".format(prior, rule, " & ".join(cells))

    for i, (agent, prior, rule) in enumerate(FACTORIAL):
        if i and i % 3 == 0:
            lines.append("    \\addlinespace\n")
        lines.append(row(agent, prior if i % 3 == 0 else "", rule))
    if po is not None:
        lines += ["    \\midrule\n"]
        for j, (model, label) in enumerate(PRIOR_ONLY):
            cells = []
            for setting in SETTINGS:
                sub = po[(po.setting == setting) & np.isclose(po["eval"], po[po.setting == setting]["eval"].median())]
                w = sub.pivot(index="episode", columns="model", values="nlpd")
                cells += [_cell(w, model, ref="gig-poisson"), ""]
            lines.append("    {} & no counts & {} \\\\\n".format(label, " & ".join(cells)))
    lines += ["    \\midrule\n"]
    for agent, prior, rule in ESTIMATORS:
        lines.append(row(agent, prior, rule))
    lines += ["    \\bottomrule\n", "\\end{tabular}\n"]
    return "".join(lines)


#: Overhead levels per setting (results prefix ``fact_ovh<c0>_``), in the setting's unit, and
#: the shortest action they are compared with.
OVERHEADS = {"bulk": ((0.5, 2.0), 1.0, "m$^3$"), "gamma": ((0.25, 1.0), 0.5, "Ms"),
             "hardxray": ((0.25, 1.0), 0.5, "ks")}
NAMES = {"bulk": "diamonds", "gamma": "$\\gamma$-ray survey", "hardxray": "hard X-ray"}


def overhead():
    """Per setting and overhead c0: how often the EIG and D-optimality take a longer dwell than
    the shortest, the NLPD and top-5 regret area of the EIG, and the paired differences of
    D-optimality and the systematic programme from it (positive = worse than the EIG)."""
    lines = [HEADER, "\\begin{tabular}{ll cc cc cc}\n", "    \\toprule\n",
             "    & & \\multicolumn{2}{c}{longer dwells} & \\multicolumn{2}{c}{NLPD} & "
             "\\multicolumn{2}{c}{top-$5$ regret area} \\\\\n",
             "    \\cmidrule(lr){3-4} \\cmidrule(lr){5-6} \\cmidrule(lr){7-8}\n",
             "    setting & $c_0$ & EIG & D-opt. & EIG & D-opt. $-$ EIG & EIG & D-opt. $-$ EIG \\\\\n",
             "    \\midrule\n"]
    for setting in SETTINGS:
        levels, shortest, unit = OVERHEADS[setting]
        for c0 in levels:
            prefix = "fact_ovh{:g}_".format(c0)
            path = os.path.join(RESULTS, prefix + setting + ".csv")
            if not os.path.exists(path):
                continue
            d = pd.read_csv(path)
            fin = d[np.isclose(d.spent, d.spent.max())]
            w = wide(fin, "nlpd")
            auc = d.groupby(["episode", "agent"]).regret_top5.mean().unstack("agent")
            longer = 1.0 - fin.groupby("agent").frac_shortest.mean()
            if "eig" not in w or "d-optimality" not in w:
                continue
            lines.append("    {} & ${:g}$ {} & ${:.0f}\\%$ & ${:.0f}\\%$ & {} & {} & {} & {} \\\\\n".format(
                NAMES[setting], c0, unit, 100 * longer.get("eig", np.nan),
                100 * longer.get("d-optimality", np.nan), _cell(w, "eig"),
                _cell(w, "d-optimality"), _cell(auc, "eig"), _cell(auc, "d-optimality")))
    lines += ["    \\bottomrule\n", "\\end{tabular}\n"]
    return "".join(lines)


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, text in (("small_catalogue", small_catalogue()), ("lsn", lsn()),
                       ("factorial", factorial()), ("overhead", overhead())):
        path = os.path.join(OUT, name + ".tex")
        with open(path, "w") as fh:
            fh.write(text)
        print("wrote {}".format(os.path.relpath(path, ROOT)))


if __name__ == "__main__":
    main()
